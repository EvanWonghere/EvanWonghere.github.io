const decode = (pattern) => pattern.split('/').map((row) => Array.from(row, Number));
const roundedUpscale = (solution) => {
    const result = Array.from({ length: 15 }, () => Array(15).fill(0));
    for (let row = 0; row < 5; row++) for (let col = 0; col < 5; col++) {
        if (!solution[row][col]) continue;
        for (let y = 0; y < 3; y++) for (let x = 0; x < 3; x++) result[row * 3 + y][col * 3 + x] = 1;
        const up = solution[row - 1]?.[col];
        const down = solution[row + 1]?.[col];
        const left = solution[row]?.[col - 1];
        const right = solution[row]?.[col + 1];
        if (!up && !left) result[row * 3][col * 3] = 0;
        if (!up && !right) result[row * 3][col * 3 + 2] = 0;
        if (!down && !left) result[row * 3 + 2][col * 3] = 0;
        if (!down && !right) result[row * 3 + 2][col * 3 + 2] = 0;
    }
    return result;
};

